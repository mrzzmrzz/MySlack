//go:build ignore

// Emoji writes slack/emoji_table.go from emoji-datasource's emoji.json:
//
//	curl -sSLo emoji.json https://cdn.jsdelivr.net/npm/emoji-datasource@15.1.2/emoji.json
//	go run internal/gen/emoji.go emoji.json
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	var list []struct {
		Unified    string   `json:"unified"`
		ShortNames []string `json:"short_names"`
	}
	if err := json.Unmarshal(data, &list); err != nil {
		panic(err)
	}
	m := map[string]string{}
	for _, e := range list {
		var s strings.Builder
		for _, h := range strings.Split(e.Unified, "-") {
			r, _ := strconv.ParseUint(h, 16, 32)
			s.WriteRune(rune(r))
		}
		for _, n := range e.ShortNames {
			m[n] = s.String()
		}
	}
	for i, tone := range []string{"1F3FB", "1F3FC", "1F3FD", "1F3FE", "1F3FF"} {
		r, _ := strconv.ParseUint(tone, 16, 32)
		m[fmt.Sprintf("skin-tone-%d", i+2)] = string(rune(r))
	}
	names := make([]string, 0, len(m))
	for n := range m {
		names = append(names, n)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Code generated by internal/gen/emoji.go; DO NOT EDIT.\n\npackage slack\n\nvar emojiTable = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "%q: %q,\n", n, m[n])
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	os.WriteFile("slack/emoji_table.go", src, 0o644)
}
